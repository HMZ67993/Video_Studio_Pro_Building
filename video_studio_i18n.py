def tr(key: str, lang: str = "ar", **kwargs) -> str:
    pair = TRANSLATIONS.get(key)
    text = (pair[0] if lang == "ar" else pair[1]) if pair else key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text


import re as _re

_DEFAULT_TRACK_RE = _re.compile(r"^(Video|Text|Audio|Sticker|Stickers|Image)(?:\s+(\d+))?$")
_TRACK_TYPE_KEYS = {"video": "track_video", "text": "track_text", "audio": "track_audio", "sticker": "track_sticker"}


def track_display_name(track, lang: str = "ar") -> str:
    """Track label in the UI language. Default names ("Video 1", "Sticker 2", old "Stickers") are translated;
    names the user typed are shown as they are."""
    name = str(getattr(track, "name", "") or "")
    m = _DEFAULT_TRACK_RE.match(name.strip())
    ttype = str(getattr(track, "track_type", "video"))
    if m:
        n = m.group(2)
        label = tr(_TRACK_TYPE_KEYS.get(ttype, "track_video"), lang)
        return f"{label} {n}" if n else label
    return name or tr(_TRACK_TYPE_KEYS.get(ttype, "track_video"), lang)
